-- Postgres schema for Ainos (used in production on Supabase).
-- Mirrors the SQLite schema in db.js. Timestamps are epoch milliseconds (BIGINT).
-- Row Level Security is enabled with no policies on every table, so Supabase's
-- public Data API (anon / authenticated keys) can read nothing; the app server
-- connects with its own role that bypasses RLS.
--
-- This file is also the migration: every statement must be safe to re-run on a
-- live database. It is applied by the tables' owner (Supabase SQL editor, or
-- the build when DATABASE_MIGRATION_URL is set); every deploy then checks, as
-- the app's role, that each table and column below exists (seed-postgres.js).
-- ALTER TABLE locks the whole table even when it changes nothing, so changes
-- to existing tables go in DO blocks that check first.

CREATE TABLE IF NOT EXISTS users (
  id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  username      TEXT NOT NULL,
  display_name  TEXT NOT NULL,
  password_hash TEXT,
  language      TEXT NOT NULL DEFAULT 'en',
  is_simulated  INTEGER NOT NULL DEFAULT 0,
  created_at    BIGINT NOT NULL
);
CREATE UNIQUE INDEX IF NOT EXISTS users_username_ci ON users (lower(username));

CREATE TABLE IF NOT EXISTS sessions (
  token_hash TEXT PRIMARY KEY,
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at BIGINT NOT NULL,
  expires_at BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expires ON sessions(expires_at);

CREATE TABLE IF NOT EXISTS artists (
  id       TEXT PRIMARY KEY,
  name     TEXT NOT NULL,
  genre    TEXT NOT NULL,
  language TEXT NOT NULL DEFAULT 'en',
  bio      TEXT NOT NULL DEFAULT '',
  image    TEXT NOT NULL,
  color    TEXT NOT NULL
);

CREATE TABLE IF NOT EXISTS albums (
  id          TEXT PRIMARY KEY,
  artist_id   TEXT NOT NULL REFERENCES artists(id),
  title       TEXT NOT NULL,
  year        INTEGER NOT NULL,
  type        TEXT NOT NULL DEFAULT 'album',
  cover       TEXT NOT NULL,
  color       TEXT NOT NULL,
  released_at BIGINT NOT NULL
);

CREATE TABLE IF NOT EXISTS tracks (
  id               TEXT PRIMARY KEY,
  album_id         TEXT NOT NULL REFERENCES albums(id),
  artist_id        TEXT NOT NULL REFERENCES artists(id),
  title            TEXT NOT NULL,
  track_no         INTEGER NOT NULL,
  duration_ms      INTEGER NOT NULL,
  genre            TEXT NOT NULL,
  language         TEXT NOT NULL DEFAULT 'en',
  loudness_lufs    DOUBLE PRECISION NOT NULL,
  peak_db          DOUBLE PRECISION NOT NULL,
  tempo            DOUBLE PRECISION NOT NULL,
  key              INTEGER NOT NULL,
  mode             INTEGER NOT NULL,
  energy           DOUBLE PRECISION NOT NULL,
  valence          DOUBLE PRECISION NOT NULL,
  danceability     DOUBLE PRECISION NOT NULL,
  acousticness     DOUBLE PRECISION NOT NULL,
  instrumentalness DOUBLE PRECISION NOT NULL
);
CREATE INDEX IF NOT EXISTS tracks_album ON tracks(album_id, track_no);
CREATE INDEX IF NOT EXISTS tracks_artist ON tracks(artist_id);
CREATE INDEX IF NOT EXISTS tracks_language ON tracks(language);

CREATE TABLE IF NOT EXISTS track_files (
  track_id     TEXT NOT NULL REFERENCES tracks(id),
  quality      TEXT NOT NULL,
  file         TEXT NOT NULL,
  mime         TEXT NOT NULL,
  bytes        INTEGER NOT NULL,
  sample_rate  INTEGER NOT NULL,
  bitrate_kbps INTEGER NOT NULL,
  header_bytes INTEGER NOT NULL,
  PRIMARY KEY (track_id, quality)
);

CREATE TABLE IF NOT EXISTS playlists (
  id          TEXT PRIMARY KEY,
  owner_id    BIGINT REFERENCES users(id) ON DELETE CASCADE,
  name        TEXT NOT NULL,
  description TEXT NOT NULL DEFAULT '',
  color       TEXT NOT NULL DEFAULT '#5b4bdb',
  is_public   INTEGER NOT NULL DEFAULT 1,
  created_at  BIGINT NOT NULL,
  updated_at  BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS playlists_owner ON playlists(owner_id);

CREATE TABLE IF NOT EXISTS playlist_tracks (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  playlist_id TEXT NOT NULL REFERENCES playlists(id) ON DELETE CASCADE,
  track_id    TEXT NOT NULL REFERENCES tracks(id),
  position    INTEGER NOT NULL,
  added_at    BIGINT NOT NULL
);

-- One track per position. Deferred to commit, so a reorder can pass through
-- duplicates within its one UPDATE. Databases created before this constraint
-- get their positions renumbered first, in case concurrent adds left duplicates.
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_constraint WHERE conrelid = 'playlist_tracks'::regclass AND conname = 'playlist_tracks_position_key') THEN
    UPDATE playlist_tracks pt SET position = r.n - 1
      FROM (SELECT id, ROW_NUMBER() OVER (PARTITION BY playlist_id ORDER BY position, id) AS n FROM playlist_tracks) r
      WHERE r.id = pt.id AND pt.position <> r.n - 1;
    ALTER TABLE playlist_tracks ADD CONSTRAINT playlist_tracks_position_key UNIQUE (playlist_id, position) DEFERRABLE INITIALLY DEFERRED;
    DROP INDEX IF EXISTS playlist_tracks_pos; -- the constraint's own index replaces it
  END IF;
END $$;

CREATE TABLE IF NOT EXISTS liked_tracks (
  user_id  BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  track_id TEXT NOT NULL REFERENCES tracks(id),
  added_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, track_id)
);

CREATE TABLE IF NOT EXISTS followed_artists (
  user_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  artist_id TEXT NOT NULL REFERENCES artists(id),
  added_at  BIGINT NOT NULL,
  PRIMARY KEY (user_id, artist_id)
);

CREATE TABLE IF NOT EXISTS events (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL,
  device_id   TEXT NOT NULL,
  type        TEXT NOT NULL,
  track_id    TEXT,
  ms_played   INTEGER,
  position_ms INTEGER,
  reason      TEXT,
  context_uri TEXT,
  client_ts   BIGINT,
  server_ts   BIGINT NOT NULL,
  payload     TEXT
);
CREATE INDEX IF NOT EXISTS events_user_ts ON events(user_id, server_ts);
CREATE INDEX IF NOT EXISTS events_type ON events(type, id);

CREATE TABLE IF NOT EXISTS streams (
  id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  track_id    TEXT NOT NULL REFERENCES tracks(id),
  ms_played   INTEGER NOT NULL,
  context_uri TEXT,
  ended_at    BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS streams_user ON streams(user_id, ended_at);
CREATE INDEX IF NOT EXISTS streams_track ON streams(track_id, ended_at);

CREATE TABLE IF NOT EXISTS generated_playlists (
  user_id     BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  kind        TEXT NOT NULL,
  period      TEXT NOT NULL,
  title       TEXT NOT NULL,
  description TEXT NOT NULL,
  track_ids   TEXT NOT NULL,
  created_at  BIGINT NOT NULL,
  PRIMARY KEY (user_id, kind, period)
);

-- Search documents (tracks, artists, albums, public playlists). Ranking is done
-- in the app, so the same code works on SQLite and Postgres.
-- folded = searchText(title, subtitle) (util.js); '' until the app fills it in.
CREATE TABLE IF NOT EXISTS search_index (
  kind     TEXT NOT NULL,
  ref_id   TEXT NOT NULL,
  title    TEXT NOT NULL,
  subtitle TEXT NOT NULL DEFAULT '',
  folded   TEXT NOT NULL DEFAULT '',
  PRIMARY KEY (kind, ref_id)
);
DO $$
BEGIN
  IF NOT EXISTS (SELECT 1 FROM information_schema.columns WHERE table_schema = current_schema() AND table_name = 'search_index' AND column_name = 'folded') THEN
    ALTER TABLE search_index ADD COLUMN folded TEXT NOT NULL DEFAULT '';
  END IF;
END $$;

-- Fixed-window rate limits (auth.js), shared by every server instance.
CREATE TABLE IF NOT EXISTS rate_limits (
  key          TEXT PRIMARY KEY,
  window_start BIGINT NOT NULL,
  hits         INTEGER NOT NULL
);

-- Who did what to a church's data (audit.js). No foreign keys: rows outlive
-- the users and orgs they mention (account deletion, Phase 5, will anonymize them).
CREATE TABLE IF NOT EXISTS audit_log (
  id          TEXT PRIMARY KEY,
  org_id      TEXT,
  user_id     BIGINT,
  action      TEXT NOT NULL,
  target_type TEXT,
  target_id   TEXT,
  details     TEXT,
  created_at  BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS audit_log_org ON audit_log(org_id, created_at);

-- Songs: what is sung (title, lyrics), separate from the recordings that play
-- it (song_sources). org_id NULL = global catalog; otherwise private to that
-- church (orgs arrive in Phase 5, so org_id has no foreign key; checked in code).
CREATE TABLE IF NOT EXISTS songs (
  id            TEXT PRIMARY KEY,
  title         TEXT NOT NULL,
  artist        TEXT NOT NULL,
  language      TEXT NOT NULL,
  ccli_number   TEXT,
  public_domain INTEGER NOT NULL DEFAULT 0,
  org_id        TEXT,
  created_by    BIGINT,
  created_at    BIGINT NOT NULL,
  updated_at    BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS songs_org ON songs(org_id);
CREATE INDEX IF NOT EXISTS songs_language ON songs(language);

-- Other titles, transliterations and translations a song is searched by.
CREATE TABLE IF NOT EXISTS song_aliases (
  song_id TEXT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
  alias   TEXT NOT NULL,
  folded  TEXT NOT NULL,
  PRIMARY KEY (song_id, folded)
);

-- Theme and season tags, from the closed list in songs.js.
CREATE TABLE IF NOT EXISTS song_themes (
  song_id TEXT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
  theme   TEXT NOT NULL,
  PRIMARY KEY (song_id, theme)
);
CREATE INDEX IF NOT EXISTS song_themes_theme ON song_themes(theme);

-- How to play a song: a native track or a YouTube video, exactly one of them.
-- The check is named so a later phase can replace it (uploads, Phase 7).
CREATE TABLE IF NOT EXISTS song_sources (
  id               TEXT PRIMARY KEY,
  song_id          TEXT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
  source           TEXT NOT NULL CHECK (source IN ('ainos', 'youtube')),
  track_id         TEXT REFERENCES tracks(id),
  youtube_video_id TEXT,
  kind             TEXT,
  available        INTEGER NOT NULL DEFAULT 1,
  last_checked_at  BIGINT,
  CONSTRAINT song_sources_one_source CHECK ((source = 'ainos' AND track_id IS NOT NULL AND youtube_video_id IS NULL) OR (source = 'youtube' AND youtube_video_id IS NOT NULL AND track_id IS NULL))
);
CREATE INDEX IF NOT EXISTS song_sources_song ON song_sources(song_id);
CREATE INDEX IF NOT EXISTS song_sources_track ON song_sources(track_id);
CREATE UNIQUE INDEX IF NOT EXISTS song_sources_youtube ON song_sources(youtube_video_id);

-- Lyrics, once per section per language; lines are newline-separated.
-- folded = searchText(lines) for lyric search. Church-pasted lyrics carry
-- their org_id. UNIQUE treats NULLs as distinct, so global rows get their own
-- partial unique index.
CREATE TABLE IF NOT EXISTS song_sections (
  id       TEXT PRIMARY KEY,
  song_id  TEXT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
  language TEXT NOT NULL,
  label    TEXT NOT NULL,
  lines    TEXT NOT NULL,
  folded   TEXT NOT NULL DEFAULT '',
  org_id   TEXT
);
CREATE UNIQUE INDEX IF NOT EXISTS song_sections_org ON song_sections(song_id, language, label, org_id);
CREATE UNIQUE INDEX IF NOT EXISTS song_sections_global ON song_sections(song_id, language, label) WHERE org_id IS NULL;

-- The order sections are sung in, e.g. ["V1","C","V2","C"] (JSON text).
CREATE TABLE IF NOT EXISTS song_arrangements (
  id            TEXT PRIMARY KEY,
  song_id       TEXT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
  org_id        TEXT,
  name          TEXT NOT NULL,
  section_order TEXT NOT NULL
);
CREATE INDEX IF NOT EXISTS song_arrangements_song ON song_arrangements(song_id);

-- Scripture a song draws on, as USFM references (ROM.12.1); section_label
-- NULL = the whole song. Only references are stored, never verse text.
CREATE TABLE IF NOT EXISTS song_scripture (
  song_id       TEXT NOT NULL REFERENCES songs(id) ON DELETE CASCADE,
  section_label TEXT,
  usfm_ref      TEXT NOT NULL,
  position      INTEGER NOT NULL,
  PRIMARY KEY (song_id, usfm_ref)
);

-- Per-user settings as key/value pairs (e.g. bible_version), so new settings
-- need no new users column.
CREATE TABLE IF NOT EXISTS user_settings (
  user_id    BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  key        TEXT NOT NULL,
  value      TEXT NOT NULL,
  updated_at BIGINT NOT NULL,
  PRIMARY KEY (user_id, key)
);

-- [3] YouTube video data (official worship videos). YouTube's terms: refresh or
-- delete within 30 days (fetched_at).
CREATE TABLE IF NOT EXISTS youtube_video_cache (
  video_id         TEXT PRIMARY KEY,
  channel_id       TEXT,
  title            TEXT,
  channel_title    TEXT,
  thumbnail_url    TEXT,
  duration_ms      INTEGER,
  embeddable       INTEGER,
  default_language TEXT,
  fetched_at       BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS youtube_video_cache_fetched ON youtube_video_cache(fetched_at);

-- [4] Time-synced lyrics for ONE recording (song_sources row). timings: JSON
-- [{ label, line, ms }]. org_id set = a church's private timings.
CREATE TABLE IF NOT EXISTS lyric_timings (
  id             TEXT PRIMARY KEY,
  source_id      TEXT NOT NULL REFERENCES song_sources(id) ON DELETE CASCADE,
  language       TEXT NOT NULL,
  arrangement_id TEXT,
  offset_ms      INTEGER NOT NULL DEFAULT 0,
  timings        TEXT NOT NULL,
  created_by     BIGINT,
  org_id         TEXT,
  updated_at     BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS lyric_timings_source ON lyric_timings(source_id);

-- [5] Churches and their members (roles: admin, leader, operator, member).
CREATE TABLE IF NOT EXISTS orgs (
  id               TEXT PRIMARY KEY,
  name             TEXT NOT NULL,
  default_language TEXT NOT NULL,
  bible_version_id INTEGER,
  created_by       BIGINT NOT NULL,
  created_at       BIGINT NOT NULL
);
CREATE TABLE IF NOT EXISTS org_members (
  org_id    TEXT NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
  user_id   BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  role      TEXT NOT NULL CHECK (role IN ('admin', 'leader', 'operator', 'member')),
  joined_at BIGINT NOT NULL,
  PRIMARY KEY (org_id, user_id)
);
CREATE INDEX IF NOT EXISTS org_members_user ON org_members(user_id);

-- [5] Sunday setlists. Items are replaced as a whole list, so (setlist_id,
-- position) needs no deferred constraint.
CREATE TABLE IF NOT EXISTS setlists (
  id           TEXT PRIMARY KEY,
  org_id       TEXT NOT NULL REFERENCES orgs(id) ON DELETE CASCADE,
  name         TEXT NOT NULL,
  service_date TEXT,
  created_by   BIGINT,
  updated_at   BIGINT NOT NULL
);
CREATE INDEX IF NOT EXISTS setlists_org ON setlists(org_id, service_date);
CREATE TABLE IF NOT EXISTS setlist_items (
  id             TEXT PRIMARY KEY,
  setlist_id     TEXT NOT NULL REFERENCES setlists(id) ON DELETE CASCADE,
  position       INTEGER NOT NULL,
  kind           TEXT NOT NULL CHECK (kind IN ('song', 'scripture', 'text', 'blank')),
  song_id        TEXT,
  arrangement_id TEXT,
  source_id      TEXT,
  usfm_ref       TEXT,
  text           TEXT,
  UNIQUE (setlist_id, position)
);

-- The app connects as ainos_app, which can only read and write rows; this file
-- is applied by the tables' owner. New tables need the same grant.
DO $$
BEGIN
  IF EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'ainos_app') THEN
    GRANT SELECT, INSERT, UPDATE, DELETE ON rate_limits, audit_log, songs, song_aliases, song_themes, song_sources, song_sections,
      song_arrangements, song_scripture, user_settings, youtube_video_cache, lyric_timings, orgs, org_members,
      setlists, setlist_items TO ainos_app;
  END IF;
END $$;

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['users', 'sessions', 'artists', 'albums', 'tracks', 'track_files', 'playlists', 'playlist_tracks',
                           'liked_tracks', 'followed_artists', 'events', 'streams', 'generated_playlists', 'search_index', 'rate_limits',
                           'audit_log', 'songs', 'song_aliases', 'song_themes', 'song_sources', 'song_sections', 'song_arrangements',
                           'song_scripture', 'user_settings', 'youtube_video_cache', 'lyric_timings', 'orgs',
                           'org_members', 'setlists', 'setlist_items'] LOOP
    IF NOT (SELECT relrowsecurity FROM pg_class WHERE oid = t::regclass) THEN
      EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    END IF;
  END LOOP;
END $$;
