// Build server/scripture-fallback.js: the public-domain verse text Scripture
// falls back to when YouVersion can't be used (no key, an error, a timeout,
// or a version the key may not use). AINOS-SPEC.md Phase 2.1.
//
//   node scripts/build-scripture-fallback.js path/to/engwebp_vpl.xml
//
// The input is the World English Bible from eBible.org (SOURCE_URL below,
// unzipped). Only the verses Ainos references are bundled: every hymn's
// Scripture (scripts/hymns.js) and the Verse of the Day fallback list below,
// so the file stays small. Re-run after changing either list.
import fs from 'node:fs';
import path from 'node:path';
import crypto from 'node:crypto';
import { fileURLToPath } from 'node:url';
import { HYMNS } from './hymns.js';
import { usfmRef } from '../server/validate.js';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const OUT = path.join(ROOT, 'server', 'scripture-fallback.js');
const SOURCE_URL = 'https://ebible.org/Scriptures/engwebp_vpl.zip';

// Verse of the Day when YouVersion's can't be shown: one per day of the
// year, in turn. Well-known verses, chosen by hand.
const VOTD_FALLBACK = [
  'JHN.3.16', 'PSA.23.1', 'ROM.8.28', 'PHP.4.6-7', 'ISA.40.31', 'JER.29.11', 'PRO.3.5-6', 'MAT.11.28', 'ROM.12.2', '2CO.5.17',
  'GAL.2.20', 'EPH.2.8-9', 'PSA.46.1', 'PSA.119.105', 'JOS.1.9', 'ROM.15.13', 'HEB.11.1', '1JN.4.19', 'LAM.3.22-23', 'MAT.6.33',
  'PSA.27.1', 'ISA.41.10', 'JHN.14.6', 'ROM.5.8', '1PE.5.7', 'PSA.37.4', 'COL.3.23', 'MIC.6.8', 'ZEP.3.17', '2TI.1.7', 'PSA.100.4-5',
];

/** The verse keys ("BOOK.C.V") a reference covers; whole chapters are not bundled. */
export function verseKeys(ref) {
  const [book, chapter, verses] = usfmRef(ref).split('.');
  if (!verses) throw new Error(`${ref}: whole chapters are not bundled`);
  const [from, to = from] = verses.split('-').map(Number);
  return Array.from({ length: to - from + 1 }, (_, i) => `${book}.${chapter}.${from + i}`);
}

const decode = (s) => s.replace(/&(amp|lt|gt|quot|apos|#(\d+)|#x([0-9a-f]+));/gi, (m, name, dec, hex) =>
  dec ? String.fromCodePoint(Number(dec)) : hex ? String.fromCodePoint(parseInt(hex, 16)) : { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'" }[name.toLowerCase()]);

function main(xmlFile) {
  if (!xmlFile) throw new Error('usage: node scripts/build-scripture-fallback.js path/to/engwebp_vpl.xml');
  const xml = fs.readFileSync(xmlFile, 'utf8');
  const all = new Map();
  for (const m of xml.matchAll(/<v b="([0-9A-Z]{3})" c="(\d+)" v="(\d+)">([^<]*)<\/v>/g)) all.set(`${m[1]}.${m[2]}.${m[3]}`, decode(m[4]).trim());
  if (all.size < 31000) throw new Error(`only ${all.size} verses parsed from ${xmlFile}; expected the whole Bible`);

  const refs = [...new Set([...HYMNS.flatMap((h) => h.scripture), ...VOTD_FALLBACK])];
  const verses = {};
  for (const ref of refs) {
    for (const key of verseKeys(ref)) {
      if (!all.has(key)) throw new Error(`${ref}: verse ${key} not in the source`);
      verses[key] = all.get(key);
    }
  }
  const sorted = Object.fromEntries(Object.entries(verses).sort(([a], [b]) => a.localeCompare(b)));
  const sha256 = crypto.createHash('sha256').update(xml).digest('hex');
  const source = {
    abbreviation: 'WEB',
    title: 'World English Bible',
    language: 'en',
    copyright: 'Public domain',
    license: 'Public domain (dedicated by its translators; "World English Bible" is a trademark of eBible.org)',
    url: SOURCE_URL,
    file: path.basename(xmlFile),
    sha256,
  };
  const out = `// Generated by scripts/build-scripture-fallback.js; do not edit by hand.
// Public-domain fallback text for Scripture (AINOS-SPEC.md Phase 2.1): the
// World English Bible, only the verses Ainos references. Never stored in a
// database; served when YouVersion can't be used, with this attribution.

export const FALLBACK_SOURCE = ${JSON.stringify(source, null, 2)};

/** Verse of the Day when YouVersion's can't be shown, one per day in turn. */
export const VOTD_FALLBACK = ${JSON.stringify(VOTD_FALLBACK)};

/** "BOOK.C.V" → verse text. */
export const FALLBACK_VERSES = ${JSON.stringify(sorted, null, 2)};
`;
  fs.writeFileSync(OUT, out);
  console.log(`✓ ${path.relative(ROOT, OUT)}: ${Object.keys(sorted).length} verses for ${refs.length} references (source sha256 ${sha256.slice(0, 12)}…)`);
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) main(process.argv[2]);
